//! Audit of every S→C id (0x00–0xB4): which have a typed builder, and
//! what is known or missing for the rest.
//!
//! [`super::parse`] reads it to report why an id has no typed decode
//! ([`super::ParseError::Unbuilt`] carries the [`Status`]); the `tests`
//! module checks every row against the size rule, `server-messages.tsv`,
//! the parser and the built types. The `note` of a row says, in a few
//! words, what the layout holds or what is still missing.

/// How much of an S→C message's layout is known.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Status {
    /// Full layout known from the system that sends it: a hand-written
    /// type in [`super::messages`].
    Built,
    /// Full layout in the TSV `layout` column: a type in
    /// [`crate::generated::server`], re-exported by [`super`].
    Generated,
    /// Empty `layout` that is complete: the server writes only the id, so
    /// the message has no field (0x7E: 5 bytes sent, bytes 1–4 carry no
    /// value and are masked). No type.
    IdOnly,
    /// Some bytes are known (fields, a prefix, known byte values); not all.
    Partial,
    /// Only the size rule is known.
    Unspecified,
    /// Size 0: the id is never receivable (the size rule rejects it).
    Never,
}

/// One id's audit row.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Audit {
    /// The message id.
    pub id: u8,
    /// How much of its layout is known.
    pub status: Status,
    /// The type that builds it (or, for [`Status::Partial`], the form
    /// that is built).
    pub builder: Option<&'static str>,
    /// What the layout holds, or what is missing.
    pub note: &'static str,
}

