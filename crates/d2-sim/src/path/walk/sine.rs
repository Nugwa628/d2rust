/// trunc(T[i & 0x1FF] · r) for an integer r that float32 holds exactly
/// (|r| < 2^24), as the x87 computes it in 53-bit precision (open
/// question 9 asks whether the game runs with 24-bit
/// precision instead).
pub fn trunc_mul(i: u32, r: i64) -> i64 {
    let b = SINE_BITS[(i & 0x1FF) as usize];
    let neg = b >> 31 != 0;
    let e = ((b >> 23) & 0xFF) as i64;
    let frac = i64::from(b & 0x7F_FFFF);
    // value = m · 2^p.
    let (m, p) = if e == 0 {
        (frac, -149)
    } else {
        (frac | 0x80_0000, e - 150)
    };
    let prod = (m * r.abs()) as i128;
    let mag = if p >= 0 {
        prod << p
    } else if p > -127 {
        prod >> (-p)
    } else {
        0
    };
    let v = mag as i64;
    if neg != (r < 0) {
        -v
    } else {
        v
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    // The table is the formula's (the check uses floating point; the
    // simulation never does).
    #[test]
    fn table_is_the_float32_step_formula() {
        let s = f32::from_bits(0x3C49_0FDB);
        assert_eq!(s, (2.0 * std::f64::consts::PI / 512.0) as f32);
        for (i, &b) in SINE_BITS.iter().enumerate() {
            let v = ((i as f64) * f64::from(s)).sin() as f32;
            assert_eq!(v.to_bits(), b, "entry {i}");
        }
        // Not the plain rounding of sin(2πi/512) everywhere.
        let differ = (0..512)
            .filter(|&i| {
                let v = (2.0 * std::f64::consts::PI * i as f64 / 512.0).sin() as f32;
                v.to_bits() != SINE_BITS[i]
            })
            .count();
        assert_eq!(differ, 328);
    }

    #[test]
    fn trunc_mul_equals_the_exact_double_product() {
        for i in 0..512u32 {
            for r in [0i64, 1, 9600, 9600 * 77, -9600 * 13, 255, (1 << 24) - 1] {
                let t = f64::from(f32::from_bits(SINE_BITS[i as usize]));
                let want = (t * r as f64).trunc() as i64;
                assert_eq!(trunc_mul(i, r), want, "i {i} r {r}");
            }
        }
    }
}
