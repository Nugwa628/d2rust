//! Typed game data for D2RUST: the Diablo II data tables, read from the player's own
//! game files.
//!
//! The crate turns the game's `.txt` sheets and compiled `.bin` tables into typed
//! records for the simulation and the server, and applies mod patch layers to the
//! player's tables at load time. It does not depend on Bevy. The modules:
//!
//! - [`txt`]: strict `.txt` reader and column binding.
//! - [`schema`]: the field lists and loader calls (`fields.tsv`, `tables.tsv`).
//! - [`compile`]: field types, linkers and callbacks that turn `.txt` cells into
//!   record bytes.
//! - [`calc`]: formula compiler and code buffers (item and skill expressions).
//! - [`strings`]: string tables and the `strkey` resolver.
//! - [`compile_set`]: every table, compiled in load order.
//! - [`bin`]: the `.bin` container, live-file resolution and post-load checks.
//! - [`crosscheck`]: compares compiled text with the live `.bin` files.
//! - [`fixup`]: post-load fix-ups and the runtime maps built from them.
//! - [`tables`]: typed records, generated by [`codegen`] from the schema.
//! - [`links`]: cross-reference validation between tables.
//! - [`patch`]: mod patch layers applied over the `.txt` cells.
//! - [`sounds`]: the runtime `sounds.txt` and `soundenviron.txt` tables.

pub mod bin;
