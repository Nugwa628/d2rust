//! The quest-log entry table and the 27 status tables.
//! Data only; the derivation is in the
//! parent module.

/// String id of `qstsnull`: the "invalid state" row.
pub const NULL_STRING: u16 = 3725;
/// String id of `qstsxxx`: the placeholder title.
pub const PLACEHOLDER_STRING: u16 = 3724;

/// One 64-byte status table. `rows[s]` is `(description text id,
/// replay speech id)` for status s = 1…14; `rows[0]` is the null pair (the
/// words 1–2 of row 0 are `completed` and `pending`).
#[derive(Debug, Clone, Copy)]
pub struct QuestTable {
    /// Entry = quest id.
    pub entry: u8,
    /// Server chain of the entry (+8).
    pub chain: u8,
    /// Act tab 0–4 (+3). The entries name the act number 1–5.
    pub tab: u8,
    /// Slot within the act tab (+2).
    pub slot: u8,
    /// Icon index 0–26 (+1).
    pub icon: u8,
    /// Word 0: title string id.
    pub title: u16,
    /// Word 1: completed speech.
    pub completed: u16,
    /// Word 2: reward-pending step p (0xFFFF = none).
    pub pending: u16,
    pub rows: [(u16, u16); 15],
}

impl QuestTable {
    /// Row s as `(text, speech)`; a status past the table (>= 15) is read as
    /// a null row (no server sends one).
    pub fn row(&self, s: u8) -> (u16, u16) {
        self.rows
            .get(s as usize)
            .copied()
            .unwrap_or((NULL_STRING, NULL_STRING))
    }
}

/// One of the 41 quest-log entries.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Entry {
    pub enabled: bool,
    pub icon: u8,
    pub slot: u8,
    /// Act tab 0–4; 9 = none.
    pub tab: u8,
    /// Server chain; 37 = none.
    pub chain: u8,
    /// Quest id q (= the entry index).
    pub filter: u8,
}

pub const ENTRY_COUNT: usize = 41;
/// Tab value of an entry shown in no tab.
pub const TAB_NONE: u8 = 9;
/// Chain value of an entry with no server chain.
pub const CHAIN_NONE: u8 = 37;

/// Entry i of the quest-log entry table. Disabled entries: tab 9, chain 37, except entry 34
/// (chain 30, tab 4: the respec quest, never shown).
pub fn entry(i: u8) -> Entry {
    if let Some(t) = table_of(i) {
        return Entry {
            enabled: true,
            icon: t.icon,
            slot: t.slot,
            tab: t.tab,
            chain: t.chain,
            filter: i,
        };
    }
    let (tab, chain) = if i == 34 {
        (4, 30)
    } else {
        (TAB_NONE, CHAIN_NONE)
    };
    Entry {
        enabled: false,
        icon: 0,
        slot: 0,
        tab,
        chain,
        filter: i,
    }
}

/// The status table of entry `i`, `None` for a disabled entry.
pub fn table_of(i: u8) -> Option<&'static QuestTable> {
    TABLES.iter().find(|t| t.entry == i)
}

/// The first entry (0…40) whose server chain is `chain` (chain 37 means none),
/// `None` = −1.
pub fn chain_entry(chain: u8) -> Option<u8> {
    if chain == CHAIN_NONE {
        return None;
    }
    (0..ENTRY_COUNT as u8).find(|&i| entry(i).chain == chain)
}

