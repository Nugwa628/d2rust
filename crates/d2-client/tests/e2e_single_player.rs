//! End-to-end single player: the bridge (`d2_client::bridge`) on its
//! local link (`bridge::local::LocalLink`) over the in-process
//! `d2-server` host, whose game is `SimGame` on the fully wired `d2-sim`
//! (`wiring::worldgen::WorldSim` around `wiring::action::ActionSim`),
//! from synthetic tables and synthetic DS1 files (no game files).
//!
//! The run, step by step (each step says where it stops and why):
//!
//! 1. game creation on a fixed seed: act 0's DRLG through the level-type
//!    dispatcher (`WorldTypes`: the Act I outdoor placer, preset inits),
//!    the regions on the game seed;
//! 2. a preset level generated by the real generator (`drlg::preset`),
//!    one of its rooms streamed for the player;
//! 3. the player joins; the first host tick runs the client room change
//!    (rooms near the player become active) and the room
//!    pass (the DS1's preset monster is created);
//! 4. a right-skill cast at the monster (C→S 0x0C): the handler runs, the
//!    mode starts and its animation schedule
//!    reads the AnimData record of the unit's composed COF name;
//!    the action frame (event 0) runs the do
//!    function and the real missile creation; the missile flies, hits,
//!    kills: the death mode with its
//!    target and the player's experience;
//! 5. (a) the death start drops gold through the treasure walk as a real
//!    item unit in the monster's room; the
//!    kill's experience levels the player up;
//!    then (step 7) a stat point is spent (C→S 0x3A);
//!    (step 5b) pick-up of that gold (C→S 0x16, pick-up to the cursor,
//!    then gold): the drop created it in the game's one item store,
//!    so the item-move handler finds it and the gold is credited;
//! 8. (steps 8–10) Akara on the server's `WiredWorld` (the same units):
//!    talk (C→S 0x13: S→C 0x27, 0x29, 0x28), chat (0x2F),
//!    trade (0x38: the store generated);
//! 9. (steps 11–18) item moves on the game's one inventory model
//!    (`d2_sim::wiring::inventory` under
//!    `handlers::items::moves`): a cap on the ground is picked to the
//!    cursor (0x16), placed in the grid (0x18), lifted (0x19), equipped
//!    (0x1A), unequipped (0x1C), dropped (0x17), picked and placed
//!    again; each frame's tick sends the deferred item messages
//!    (0x9C / 0x9D with the item bit stream:
//!    decoded with `d2-proto`'s reader and cut off by `streams`) and
//!    0x47, 0x48;
//! 10. (steps 19–22) the vendor on the same inventory (the player
//!     leaves Akara for the item moves, C→S 0x30, and talks to her
//!     again first): the cap placed by 0x18 is sold (0x33: removed, freed, the price received: S→C 0x2A
//!     kind 3), a buy (0x32) copies the store cap (the purchase loop,
//!     on the inventory model) into the backpack (0x2A kind 4,
//!     its 0x9C action 4), the stored buckler is sold (a restored copy
//!     into the store), the stored cap is sold; quest requests
//!     (0x31, 0x40, 0x58) start Den of Evil, fetch its log and acknowledge
//!     its log bit, with the replies applied to the client model and UI;
//! 11. (steps 23–25) the cube (C→S 0x2A, 0x4F)
//!     on the same inventory: a ground ring picked to the cursor, put in
//!     the cube (cube placement: 0x9C action 4), transmuted (the ring's
//!     0x9D action 5 now, the amulet's 0x9C action 4 in the update
//!     pass);
//! 12. (step 6) a waypoint travel (C→S 0x49) runs through the
//!     handler, the warp seam and the destination's spawn search, **then
//!     stops**: this run keeps the path provider off (step 4's missile
//!     would get no path points with it on, blocker WP1), so the warp's
//!     placement stays `Pending`, the player is not moved and
//!     the warp sends no S→C 0x0D. With the provider on
//!     the step holds: `e2e_walk.rs` (placement, 0x07 then 0x0D).
//!
//! The S→C messages the specs lay out (0x27, 0x29, 0x28, 0x2A, 0x9C,
//! 0x9D, 0x47, 0x48) are asserted byte for byte; every other frame's
//! received bytes are asserted empty: the wiring sends no S→C message on
//! the other paths (no written spec ties a mode, missile, death, stat or
//! cube message to them yet). Where a step needs behaviour no written spec
//! owns (the COF-name composer, the animation rate, the missile's path
//! and damage setup, the death start's body, the free-spot search, the
//! cube's opening, the item-move seams of `InvFx`), the fixture answers
//! the seam and says so at the answer.
//!
//! The whole run is repeated: same seed → byte-identical transcript.

