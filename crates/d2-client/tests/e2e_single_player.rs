/// Item types of the cube's items (the cube recipe's shape).
const T_RING: u16 = 10;
const T_BOX: u16 = 11;
const T_AMULET: u16 = 12;
/// The cube's item records, after the vendor items (`CAP`, `BUC`) in the
/// game's one item table.
const CUBE_BOX: usize = 2;
const RING: usize = 3;
const AMULET: usize = 4;
/// The gold pile's record (`gld `), the drop's item.
const GOLD_REC: usize = 5;

/// The drop tables over the game's one item table (gold among the
/// vendor and cube items): the drop creates into the game's one item
/// store, which every item system reads with these records.
fn drop_tables() -> DropTables {
    drop_tables_from(game_item_tables(), GOLD_REC)
}

/// The game's item tables: the vendor items (`e2e_support::item_tables`:
/// cap, buckler) and the cube's items (`box `, a ring, an amulet; each
/// type is its own and type 0's).
fn game_item_tables() -> ItemTables {
    let mut t = item_tables();
    let rec = |ty: u16, code: &[u8; 4]| ItemRec {
        code: *code,
        type_: ty as i16,
        level: 1,
        ..ItemRec::default()
    };
    t.items.extend([
        rec(T_BOX, b"box "),
        rec(T_RING, b"rin "),
        rec(T_AMULET, b"amu "),
        rec(ty::GOLD, b"gld "),
    ]);
    // Gold is always normal quality (itemtypes `Normal`, the treasure
    // walk's first step) and misc.
    t.itemtypes[usize::from(ty::GOLD)].normal = 1;
    let (g, m, w) = (usize::from(ty::GOLD), usize::from(ty::MISC), t.equiv.words);
    t.equiv.bits[g * w + m / 32] |= 1 << (m % 32);
    t
}

/// One recipe (the cube recipe's shape without mods): one ring → a normal
/// amulet.
fn cube_data(t: &ItemTables) -> CubeData {
    let mut inputs = [InputSlot::default(); 7];
    inputs[0] = InputSlot {
        flags: input_flags::USEANY,
        item: RING as u16,
        ..InputSlot::default()
    };
    let out = OutputSlot {
        kind: kind::ITEMCODE,
        item: AMULET as u16,
        quality: q::NORMAL,
        mods: [CraftMod {
            property: -1,
            ..CraftMod::default()
        }; 5],
        ..OutputSlot::default()
    };
    CubeData {
        recipes: vec![Recipe {
            enabled: 1,
            class: 0xFF,
            numinputs: 1,
            inputs,
            outputs: [out, OutputSlot::default(), OutputSlot::default()],
            ..Recipe::default()
        }],
        items: t
            .items
            .iter()
            .map(|r| ItemRecord {
                code: r.code,
                level: r.level,
                spawnable: 1,
                ..ItemRecord::default()
            })
            .collect(),
        valshift: vec![0; 359],
        max_level: 99,
    }
}

